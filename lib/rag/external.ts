// ═══════════════════════════════════════════════════════════════════════════
// external.ts — web search via Groq's built-in "compound" system (PRD §8).
//
// Originally this called Brave Search + YouTube Data API directly, but
// those require separate API keys/accounts. Groq's `groq/compound` model
// has server-side web search built in (Tavily under the hood) and runs on
// the SAME GROQ_API_KEY already configured for the tutor — no extra
// provider setup needed. We call it purely for its structured
// `search_results` (title/url/snippet), not its own synthesized answer —
// the actual answer is still generated by our own Tutor engine (chat.ts)
// so it stays grounded in the subject persona, mode, and document context.
// ═══════════════════════════════════════════════════════════════════════════

import { getGroqClient } from './groq';

export interface WebResult { title: string; url: string; snippet: string; }
export interface YoutubeResult { title: string; channel: string; url: string; videoId: string; timestamp_s: number | null; }

function extractYoutubeId(url: string): string | null {
  const m = url.match(/(?:youtube\.com\/watch\?v=|youtu\.be\/)([\w-]{6,})/);
  return m ? m[1] : null;
}

function parseTimestamp(value: string | null): number | null {
  if (!value) return null;
  if (/^\d+$/.test(value)) return Number(value);
  const match = value.match(/^(?:(\d+)h)?(?:(\d+)m)?(?:(\d+)s)?$/i);
  if (!match || !match[0]) return null;
  return Number(match[1] || 0) * 3600 + Number(match[2] || 0) * 60 + Number(match[3] || 0);
}

function extractYoutubeTimestamp(url: string): number | null {
  try {
    const parsed = new URL(url);
    const hashTimestamp = parsed.hash.match(/(?:^#|&)t=([^&]+)/)?.[1] ?? null;
    return parseTimestamp(parsed.searchParams.get('t') ?? parsed.searchParams.get('start') ?? hashTimestamp);
  } catch {
    return null;
  }
}

// groq/compound-mini is the lighter/cheaper of Groq's two search-capable
// systems — sufficient since we only need raw search results, not its own
// multi-step reasoning. Falls back to the full groq/compound system if
// compound-mini isn't available on the account.
const SEARCH_MODELS = ['groq/compound-mini', 'groq/compound'];

export async function groqExternalSearch(
  query: string,
  count = 6,
): Promise<{ web: WebResult[]; youtube: YoutubeResult[] }> {
  const client = getGroqClient();
  let lastErr: any = null;

  for (const model of SEARCH_MODELS) {
    try {
      const completion = await client.chat.completions.create({
        model,
        messages: [{ role: 'user', content: query }],
      });

      // executed_tools/search_results are Compound-specific fields not in
      // the standard chat-completions type — cast since the SDK's base
      // types don't model them.
      const msg = completion.choices[0]?.message as any;
      const results = msg?.executed_tools?.[0]?.search_results?.results ?? [];
      if (!results.length) return { web: [], youtube: [] };

      const web: WebResult[] = [];
      const youtube: YoutubeResult[] = [];
      for (const r of results.slice(0, count)) {
        const videoId = extractYoutubeId(r.url);
        if (videoId) {
          youtube.push({ title: r.title, channel: 'YouTube', url: r.url, videoId, timestamp_s: extractYoutubeTimestamp(r.url) });
        } else {
          web.push({ title: r.title, url: r.url, snippet: r.content ?? '' });
        }
      }
      return { web, youtube };
    } catch (err) {
      lastErr = err;
      // try the next model in SEARCH_MODELS
    }
  }

  throw new Error(`Web search failed: ${lastErr?.message || 'unknown error'}`);
}
